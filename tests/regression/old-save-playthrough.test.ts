import { readFileSync } from "node:fs";
import { join } from "node:path";
import { gunzipSync } from "node:zlib";
import { describe, expect, it } from "vitest";
import { getCalendarMonthId } from "@/domain/calendar-date";
import {
  deserializeGameState,
  serializeGameState,
} from "@/persistence/mappers/game-state-mapper";
import { validateGameState } from "@/persistence/validate-game-state";
import type { GameState } from "@/state/game-state";
import { GAME_STATE_SCHEMA_VERSION } from "@/state/game-state";
import { getActivePhaseId, type LeaguePhaseId } from "@/systems/phase-engine";
import { advanceThroughPhase } from "../offseason/driver";
import { collectOffseasonInvariantIssues } from "../offseason/invariants";
import { stateForComparison } from "../offseason/snapshot";

/**
 * Played saves from recent schema versions (generated by that version's own
 * engine with `scripts/generate-golden-saves.ts --played`, stopped on the
 * first day of free agency) load, finish their offseason, play a full season
 * and a full offseason, and keep the offseason invariants at every phase.
 */
const FIXTURE_DIR = join(__dirname, "..", "fixtures", "saves");

/**
 * Damage an older engine wrote into a save, which the current engine heals
 * at the next Roster Decisions instead of on load: v65 left two players on
 * their teams with contracts that had ended (released one season late).
 */
const HISTORICAL_ISSUES: Record<string, readonly string[]> = {
  v65: [
    "ROSTER_AND_FREE_AGENT",
    "FREE_AGENT_ON_TEAM",
    "CONTRACT_EXPIRED_ON_TEAM",
  ],
  v71: [],
  v77: [],
};

const PLAYED = Object.keys(HISTORICAL_ISSUES);

/** From free agency: finish this offseason, a full season and an offseason. */
const MAX_PHASES = 24;

function loadPlayed(version: string): GameState {
  const json = gunzipSync(
    readFileSync(join(FIXTURE_DIR, `${version}-played.json.gz`)),
  ).toString("utf8");
  return deserializeGameState(json);
}

function issueCodes(
  state: GameState,
  previous: GameState,
  cashLedgerFrom: string,
): string[] {
  return collectOffseasonInvariantIssues(state, {
    previous,
    cashLedgerFrom,
  }).map((issue) => `${issue.code}: ${issue.message}`);
}

describe("old played saves", () => {
  it.each(PLAYED)(
    "%s loads, plays a full season and offseason and keeps the invariants",
    (version) => {
      const loaded = loadPlayed(version);
      expect(loaded.meta.schemaVersion).toBe(GAME_STATE_SCHEMA_VERSION);
      validateGameState(loaded);
      expect(getActivePhaseId(loaded)).toBe("offseason.free_agency");

      // The old engine's cash-journal gaps stay in its months; everything
      // this version writes, from the load month on, must reconcile.
      const ledgerFrom = getCalendarMonthId(loaded.world.calendar.currentDate);
      const allowed = new Set(HISTORICAL_ISSUES[version]);
      const atLoad = issueCodes(loaded, loaded, ledgerFrom);
      expect(
        atLoad.filter((issue) => !allowed.has(issue.split(":")[0]!)),
      ).toEqual([]);

      let state = loaded;
      let healed = allowed.size === 0;
      let regularStarts = 0;
      const visited: LeaguePhaseId[] = [];
      for (let step = 0; step < MAX_PHASES && regularStarts < 2; step += 1) {
        const from = getActivePhaseId(state);
        const next = advanceThroughPhase(state, from).state;
        const to = getActivePhaseId(next);
        visited.push(to);
        if (to === "regular") regularStarts += 1;
        if (from === "offseason.roster_decisions") healed = true;

        const issues = issueCodes(next, state, ledgerFrom);
        const unexpected = healed
          ? issues
          : issues.filter((issue) => !allowed.has(issue.split(":")[0]!));
        expect(unexpected, `${version}: ${from} -> ${to}`).toEqual([]);

        // A save made in the middle of the next offseason reloads exactly.
        if (to === "offseason.free_agency") {
          const reloaded = deserializeGameState(serializeGameState(next));
          expect(stateForComparison(reloaded)).toEqual(
            stateForComparison(next),
          );
        }
        state = next;
      }

      expect(regularStarts).toBe(2);
      expect(healed).toBe(true);
      expect(visited).toContain("offseason.draft");
      expect(visited).toContain("offseason.free_agency");
      expect(state.competition.season.year).toBe(
        loaded.competition.season.year + 2,
      );
    },
    600_000,
  );
});
